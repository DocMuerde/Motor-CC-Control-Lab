% set_stopfcn.m
% Añade un callback StopFcn a MotorCC_V3_R2025b.slx para que el motor se
% pare automáticamente (PWM = 0) cuando se detiene la simulación en Simulink.
%
% Ejecutar UNA SOLA VEZ desde la carpeta software/matlab/:
%   cd('<ruta>/Motor-CC-Control-Lab/software/matlab')
%   run('set_stopfcn.m')
%
% Después, si quieres propagar el cambio a las versiones antiguas,
% vuelve a ejecutar exportar_versiones.m.

modelo  = 'MotorCC_V3_R2025b';
carpeta = fileparts(mfilename('fullpath'));

% ── Código que se ejecutará al parar la simulación ───────────────────────────
% Busca automáticamente el objeto serialport en el workspace base
% (independientemente de cómo se llame la variable) y envía PWM = 0.
% Paquete binario: 'A'(65) + int16(0)(0,0) + '\n'(10) = 4 bytes.
% Si el puerto ya está cerrado o no existe, el watchdog del Arduino se encarga.
stopfcn = sprintf([ ...
    '%% Parar el motor al detener la simulacion (PWM = 0)\n' ...
    'try\n' ...
    '    vars = evalin(''base'', ''whos'');\n' ...
    '    serial_var = '''';\n' ...
    '    for i = 1:length(vars)\n' ...
    '        if contains(vars(i).class, ''serialport'')\n' ...
    '            serial_var = vars(i).name;\n' ...
    '            break;\n' ...
    '        end\n' ...
    '    end\n' ...
    '    if ~isempty(serial_var)\n' ...
    '        s_stop = evalin(''base'', serial_var);\n' ...
    '        write(s_stop, uint8([65, 0, 0, 10]), ''uint8'');\n' ...
    '        pause(0.05);\n' ...
    '    end\n' ...
    'catch\n' ...
    'end']);

% ── Cargar el modelo, inyectar el callback y guardar ─────────────────────────
fprintf('Cargando %s.slx ...\n', modelo);
load_system(fullfile(carpeta, [modelo '.slx']));

set_param(modelo, 'StopFcn', stopfcn);

save_system(modelo, fullfile(carpeta, [modelo '.slx']));
close_system(modelo, 0);

fprintf('Listo. StopFcn añadido a %s.slx\n', modelo);
fprintf('El motor se parara automaticamente al detener la simulacion.\n');
fprintf('\nSi quieres propagar el cambio a las versiones antiguas:\n');
fprintf('  run(''exportar_versiones.m'')\n');
